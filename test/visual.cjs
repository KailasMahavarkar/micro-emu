const { chromium } = require("playwright");
const path = require("path");
const url = "file://" + path.resolve(__dirname, "../index.html");
const out = process.argv[2];
(async () => {
  const browser = await chromium.launch();
  const errors = [];
  const open = async (w, h, scheme) => {
    const p = await browser.newPage({ viewport: { width: w, height: h }, colorScheme: scheme });
    p.on("pageerror", e => errors.push(e.message));
    await p.goto(url); await p.evaluate(() => localStorage.clear()); await p.reload();
    return p;
  };
  let p = await open(1366, 768, "light");
  await p.selectOption("#examples", "factorial");
  for (let i = 0; i < 28; i++) await p.keyboard.press("F10");
  await p.click('.viewbar [data-view="board"]');
  await p.keyboard.press("F10");
  await p.waitForTimeout(3600);
  await p.screenshot({ path: `${out}/v-push-mid.png` });
  await p.waitForTimeout(3500);
  await p.screenshot({ path: `${out}/v-push-end.png` });
  await p.close();
  p = await open(1920, 1080, "dark");
  await p.selectOption("#examples", "macros");
  await p.click('.viewbar [data-view="board"]');
  await p.selectOption("#speed", "max");
  await p.click("#run");
  await p.waitForTimeout(9000);
  await p.screenshot({ path: `${out}/v-dark-board.png` });
  await p.click("#run");
  await p.close();
  p = await open(1366, 768, "light");
  await p.selectOption("#examples", "upper");
  await p.selectOption("#speed", "max");
  await p.click("#run");
  await p.waitForTimeout(600);
  await p.keyboard.type("Hello");
  await p.waitForTimeout(300);
  await p.screenshot({ path: `${out}/v-waiting.png` });
  await p.click("#expandBtn");
  await p.waitForTimeout(300);
  await p.screenshot({ path: `${out}/v-modal.png` });
  console.log("errors:", errors.length ? errors : "none");
  await browser.close();
})();
